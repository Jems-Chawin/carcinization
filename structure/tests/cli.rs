    let (code, report, text) = declared("fleet-designed.json");
    assert_eq!(code, 0, "{text}");
    assert_eq!(report["verdict"], "pass");
    assert_eq!(
        report["hot_paths"][0]["measured"][0]["allocations_per_iteration"],
        0.0
    );
    assert_eq!(report["hot_paths"][0]["copying_constructs"], 0);

    let (code, report, text) = declared("fleet-appeasement.json");
    assert_eq!(code, 1, "{text}");
