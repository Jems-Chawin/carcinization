#[test]
fn where_a_call_cannot_be_followed_the_report_says_so() {
    // Two hard cases. `apply` is handed a closure by its caller: the clone
    // is in the closure, which is not in any function reachable from the hot
    // path. `describe` goes through a trait object: which implementation
    // runs is not known, so every one of that name is reached.
    let lib = "pub trait Shape { fn label(&self) -> String; }
pub struct Square { name: String }
pub struct Dot;
impl Shape for Square { fn label(&self) -> String { self.name.clone() } }
impl Shape for Dot { fn label(&self) -> String { String::new() } }
pub struct Sim { shape: Box<dyn Shape>, items: Vec<String>, seen: usize }
impl Sim {
    pub fn new(_n: usize) -> Sim { Sim { shape: Box::new(Dot), items: vec![String::from(\"an item with a long enough name\"); 4], seen: 0 } }
    pub fn tick(&mut self) {
        self.seen += self.shape.label().len();
        self.seen += apply(&self.items, |s| s.clone());
    }
}
impl Default for Sim { fn default() -> Sim { Sim::new(8) } }
fn apply(items: &[String], f: impl Fn(&String) -> String) -> usize { items.iter().map(|s| f(s).len()).sum() }
";
    let budget = r#", "budget": {"allocations_per_iteration": 4, "bytes_per_iteration": 200, "reason": "test"}"#;
    let (code, report, text) = run(&repo(lib, &hot("Sim::tick", budget, true), "[]"));
    assert_eq!(code, 0, "{text}");
    assert_eq!(report["verdict"], "pass_with_flags");
    let h = &report["hot_paths"][0];
    let reached: Vec<&str> = h["functions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| f["function"].as_str().unwrap())
        .collect();
    assert_eq!(
        reached,
        ["Sim::tick", "Square::label", "Dot::label", "apply"]
    );
    // The clone behind the trait is listed, under the implementation it is
    // in, although the Dot is what actually runs here.
    let square = &h["functions"][1];
    assert_eq!(square["copying"][0]["what"], ".clone()");
    // The closure is written inside `tick`, so its clone is counted there...
    assert_eq!(h["functions"][0]["copying"][0]["what"], ".clone()");
    // ...and `apply` calling `f` is reported as a call that was not followed.
    assert_eq!(h["not_followed"].as_array().unwrap().len(), 1);
    assert!(
        h["not_followed"][0]["what"]
            .as_str()
            .unwrap()
            .contains("call through the value `f`")
    );
    assert!(
        report["flags"]
            .as_array()
            .unwrap()
            .iter()
            .any(|f| f.as_str().unwrap().contains("could not be followed"))
    );
    // The measurement does not depend on following anything: four clones ran.
    assert_eq!(h["measured"][0]["allocations_per_iteration"], 4.0);
}

#[test]
fn shared_ownership_and_threads_need_to_be_accounted_for() {
    let lib = "use std::cell::RefCell;
use std::rc::Rc;
pub struct Sim { state: Rc<RefCell<u64>> }
impl Sim {
    pub fn new(_n: usize) -> Sim { Sim { state: Rc::new(RefCell::new(0)) } }
    pub fn tick(&mut self) {
        *self.state.borrow_mut() += 1;
        std::thread::scope(|_| {});
    }
}
impl Default for Sim { fn default() -> Sim { Sim::new(8) } }
";
    // A thread scope allocates once when it is entered.
    let budget = r#", "budget": {"allocations_per_iteration": 1, "bytes_per_iteration": 64, "reason": "test"}"#;
    let (code, report, text) = run(&repo(lib, &hot("Sim::tick", budget, true), "[]"));
    assert_eq!(code, 1, "{text}");
    let all = reasons(&report);
    assert!(
        all.contains("Rc<RefCell<..>> in struct Sim") && all.contains("has no stated owner (S7)"),
        "{text}"
    );
    assert!(
        all.contains("starts a thread or pool on the hot path, with no justification (S5)"),
        "{text}"
    );

    let stated = r#"[{"check": "S7", "where": "struct Sim", "construct": "Rc<RefCell<..>>", "reason": "shared with the UI thread's view"},
                     {"check": "S7", "where": "Sim::new", "construct": "Rc<RefCell<..>>", "reason": "the same one, where it is made"},
                     {"check": "S5", "where": "Sim::tick", "construct": "thread::scope", "reason": "test"}]"#;
    let (code, report, text) = run(&repo(lib, &hot("Sim::tick", budget, true), stated));
    assert_eq!(code, 0, "{text}");
    assert_eq!(
        report["shared_ownership"][0]["declared_owner"],
        "shared with the UI thread's view"
    );
}

#[test]
fn sharing_written_inside_the_shared_type_is_seen() {
    // RUST-092 to 094, the form four ports of one pilot took: the handle
    // is `Rc<State>`, the cells are fields of `State`, a field is taken
    // out through a borrow, and a helper hands out a new vector per call.
    let lib = "use std::cell::RefCell;
use std::rc::Rc;
pub struct State { bag: RefCell<Vec<u64>>, listeners: RefCell<Vec<u64>> }
pub struct Inner { listeners: Vec<u64> }
pub struct Sim { state: Rc<State>, inner: RefCell<Inner> }
impl Sim {
    pub fn new(n: usize) -> Sim {
        Sim { state: Rc::new(State { bag: RefCell::new(vec![1; n]), listeners: RefCell::new(Vec::new()) }), inner: RefCell::new(Inner { listeners: Vec::new() }) }
    }
    fn bag(&self) -> Vec<u64> { self.state.bag.borrow().to_vec() }
    pub fn tick(&mut self) {
        let listeners = std::mem::take(&mut self.inner.borrow_mut().listeners);
        let total: u64 = self.bag().iter().sum();
        let _ = (total, self.bag().len(), self.state.listeners.borrow().len());
        self.inner.borrow_mut().listeners = listeners;
    }
}
impl Default for Sim { fn default() -> Sim { Sim::new(8) } }
";
    let budget = r#", "budget": {"allocations_per_iteration": 2, "bytes_per_iteration": 2000, "reason": "the bag is copied twice"}"#;
    let (code, report, text) = run(&repo(lib, &hot("Sim::tick", budget, true), "[]"));
    assert_eq!(code, 1, "{text}");
    let all = reasons(&report);
    assert!(
        all.contains("Rc<State> (State has cell or lock fields) in struct Sim")
            && all.contains("has no stated owner (S7)"),
        "{text}"
    );
    assert!(
        all.contains(
            "`self.listeners` is taken out with mem::take through .borrow_mut() and put back"
        ),
        "{text}"
    );
    let h = &report["hot_paths"][0];
    let bag = h["functions"]
        .as_array()
        .unwrap()
        .iter()
        .find(|f| f["function"] == "Sim::bag")
        .unwrap();
    assert_eq!(bag["calls_on_the_hot_path"], 2, "{text}");
    assert_eq!(h["copying_constructs"], 1, "{text}");
    assert_eq!(
        h["calls_to_functions_that_return_a_new_collection"], 2,
        "{text}"
    );
    assert!(
        text.contains("returns a new collection and is called at 2 place(s) on the hot path"),
        "{text}"
    );

    // Stated, they pass like any other.
    let stated = r#"[{"check": "S7", "where": "struct Sim", "construct": "Rc<State> (State has cell or lock fields)", "reason": "the view holds it too"},
                     {"check": "S4", "where": "Sim::tick", "construct": "listeners", "reason": "a listener reads the simulation"}]"#;
    let (code, report, text) = run(&repo(lib, &hot("Sim::tick", budget, true), stated));
    assert_eq!(
        (code, &report["verdict"]),
        (0, &J::from("pass_with_flags")),
        "{text}"
    );
}

