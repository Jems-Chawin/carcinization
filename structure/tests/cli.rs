#[test]
fn a_field_taken_out_of_self_and_put_back_needs_a_justification() {
    // The allocation count cannot see this: a take moves, it does not
    // allocate. The construct count can.
    let (code, report, text) = run(&repo(BUFFER, &hot("Sim::tick", ZERO, true), "[]"));
    assert_eq!(code, 1, "{text}");
    assert_eq!(report["hot_paths"][0]["within_budget"], true);
    assert!(
        reasons(&report).contains("`self.buf` is taken out with mem::take and put back"),
        "{text}"
    );
    let take = &report["hot_paths"][0]["fields_taken_out_of_self"][0];
    assert_eq!(
        (&take["field"], &take["put_back"], &take["justification"]),
        (&J::from("buf"), &J::from(true), &J::Null)
    );

    let (code, report, text) = run(&repo(BUFFER, &hot("Sim::tick", ZERO, true), JUSTIFIED));
    assert_eq!(code, 0, "{text}");
    assert_eq!(report["verdict"], "pass");
    assert_eq!(
        report["hot_paths"][0]["fields_taken_out_of_self"][0]["justification"],
        "the sum borrows the buffer while total is written"
    );
    assert!(text.contains("justified: the sum borrows"), "{text}");
}

